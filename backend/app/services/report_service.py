"""
Paddy Farming Assistant - Report Service (STEP 11I.2)
Orchestrates disease detection report compilation, metadata persistence,
and non-destructive retrieval from PostgreSQL.
"""

import json
import logging
import uuid
from pathlib import Path
from datetime import datetime, timezone
from typing import Optional, Dict, Any, Tuple, Sequence

from fastapi import HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession

from app import config
from app.db.models.report import Report
from app.db.repositories.prediction_repository import PredictionRepository
from app.db.repositories.field_repository import FieldRepository
from app.db.repositories.other_repositories import ReportRepository
from app.services.pdf_report_service import PDFReportService

logger = logging.getLogger(__name__)

DISCLAIMER_TEXT = (
    "DISCLAIMER: This diagnostic advisory is generated by artificial intelligence "
    "(EfficientNet-B4 / TemporalCrossAttention) and serves solely as informational decision support. "
    "It does not constitute a guaranteed clinical diagnosis or professional agricultural certification. "
    "Field verification by a certified agronomist is recommended prior to applying chemical treatments."
)


class ReportService:
    """
    Business service for compiling disease detection diagnostic reports and managing report metadata.
    """

    def __init__(self, session: AsyncSession):
        self.session = session
        self.report_repo = ReportRepository(session)
        self.prediction_repo = PredictionRepository(session)
        self.field_repo = FieldRepository(session)

    async def generate_diagnostic_report(
        self,
        prediction_id: uuid.UUID,
        force_regenerate: bool = False,
        file_format: str = "json",
    ) -> Tuple[Report, bool]:
        """
        Compiles a disease diagnostic report from an existing PredictionHistory record.
        Handles duplicate requests idempotently unless force_regenerate is True.
        Returns tuple of (Report, is_new: bool).
        """
        # 1. Fetch prediction record
        prediction = await self.prediction_repo.get_by_id(prediction_id)
        if not prediction:
            logger.warning("Report generation rejected: Prediction '%s' not found.", prediction_id)
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Prediction record '{prediction_id}' was not found.",
            )

        # 2. Check for existing report to handle duplicates idempotently
        if not force_regenerate:
            existing_report = await self.report_repo.get_by_prediction_id(prediction_id)
            if existing_report:
                logger.info(
                    "Returning existing diagnostic report '%s' for prediction '%s'.",
                    existing_report.id,
                    prediction_id,
                )
                return existing_report, False

        # 3. Retrieve associated field details safely (if linked)
        field_external_id = None
        field_name = None
        if prediction.field_id:
            field = await self.field_repo.get_by_id(prediction.field_id)
            if field:
                field_external_id = field.external_field_id
                field_name = field.field_name

        # 4. Compile human-readable title and agronomic summary
        disease_clean = prediction.predicted_disease.replace("_", " ").title()
        conf_float = float(prediction.confidence)
        title = f"Paddy Disease Diagnostic Report — {disease_clean}"

        if prediction.is_healthy:
            advisory_note = "Leaf specimen exhibits normal healthy characteristics with no actionable disease symptoms detected."
        elif prediction.low_confidence:
            advisory_note = (
                "Confidence score is below advisory certainty threshold (< 60%). "
                "Secondary laboratory examination or field re-inspection is strongly advised."
            )
        else:
            advisory_note = (
                f"Definitive signs consistent with {disease_clean} identified. "
                "Consult local agricultural extension officers before applying any chemical fungicides or pesticides."
            )

        summary = (
            f"AI Diagnostic Report for {disease_clean} with {conf_float:.1%} confidence "
            f"using {prediction.model_name} in {prediction.prediction_mode} mode. {advisory_note}"
        )

        now_utc = datetime.now(timezone.utc)

        # 5. Build structured report metadata (strictly omitting raw GPS or private filesystem paths)
        metadata: Dict[str, Any] = {
            "prediction_id": str(prediction.id),
            "predicted_disease": prediction.predicted_disease,
            "confidence": conf_float,
            "prediction_mode": prediction.prediction_mode,
            "model_name": prediction.model_name,
            "model_version": prediction.model_version,
            "predicted_class_index": prediction.predicted_class_index,
            "is_healthy": prediction.is_healthy,
            "low_confidence": prediction.low_confidence,
            "top_k_predictions": prediction.top_k_predictions or [],
            "attention_weights": prediction.attention_weights,
            "image_sha256": prediction.image_sha256,
            "prediction_timestamp": prediction.created_at.isoformat() if prediction.created_at else None,
            "report_generated_at": now_utc.isoformat(),
            "field_id": str(prediction.field_id) if prediction.field_id else None,
            "field_external_id": field_external_id,
            "field_name": field_name,
            "farmer_question": prediction.farmer_question,
            "response_language": prediction.response_language,
            "disclaimer": DISCLAIMER_TEXT,
        }

        # Safe artifact relative key and file compilation
        report_uuid = uuid.uuid4()
        chosen_format = file_format.lower() if file_format in ("json", "pdf") else "json"

        if chosen_format == "pdf":
            pdf_bytes = PDFReportService.generate_pdf_bytes(
                report_id=report_uuid,
                metadata=metadata,
                title=title,
                summary=summary,
            )
            artifact_key = PDFReportService.save_pdf_artifact(
                report_id=report_uuid,
                prediction_id=prediction.id,
                pdf_bytes=pdf_bytes,
            )
            file_size_bytes = len(pdf_bytes)
        else:
            artifact_key = f"diagnostic/report_{prediction.id}_{report_uuid.hex[:8]}.json"
            serialized_bytes = json.dumps(metadata, default=str).encode("utf-8")
            file_size_bytes = len(serialized_bytes)
            full_json_path = config.REPORTS_STORAGE_DIR / Path(artifact_key)
            full_json_path.parent.mkdir(parents=True, exist_ok=True)
            with open(full_json_path, "wb") as f:
                f.write(serialized_bytes)

        # 6. Persist report record in PostgreSQL
        try:
            report = await self.report_repo.create_report(
                report_id=report_uuid,
                report_type="disease_diagnostic",
                title=title,
                prediction_id=prediction.id,
                field_id=prediction.field_id,
                summary=summary,
                status="completed",
                file_path=artifact_key,
                file_format=chosen_format,
                file_size_bytes=file_size_bytes,
                report_metadata=metadata,
                generated_by="system",
            )
            await self.session.commit()
            logger.info("Successfully generated and persisted report '%s' for prediction '%s'.", report.id, prediction.id)
            return report, True
        except Exception as db_err:
            await self.session.rollback()
            logger.error("Failed to persist report for prediction '%s': %s", prediction_id, db_err, exc_info=True)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Inference record found but report persistence failed due to an internal database error.",
            ) from db_err

    async def get_report_by_id(self, report_id: uuid.UUID) -> Report:
        """
        Retrieves a report record by primary key UUID.
        Falls back to prediction_id lookup or auto-generation if a prediction exists.
        Raises 404 if not found.
        """
        report = await self.report_repo.get_by_id(report_id)
        if not report:
            # Check if report_id was actually a prediction_id
            report = await self.report_repo.get_by_prediction_id(report_id)
        if not report:
            # Check if an actual prediction exists with this ID, and auto-generate the report
            pred = await self.pred_repo.get_by_id(report_id)
            if pred:
                report, _ = await self.generate_disease_diagnostic_report(
                    prediction_id=pred.id,
                    file_format="pdf",
                    force_regenerate=True,
                )
        if not report:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Report '{report_id}' was not found.",
            )
        return report

    async def list_reports(
        self,
        prediction_id: Optional[uuid.UUID] = None,
        field_id: Optional[uuid.UUID] = None,
        report_type: Optional[str] = None,
        status_filter: Optional[str] = None,
        skip: int = 0,
        limit: int = 50,
    ) -> Tuple[Sequence[Report], int]:
        """
        Lists reports with pagination and optional filters.
        """
        return await self.report_repo.list_reports(
            prediction_id=prediction_id,
            field_id=field_id,
            report_type=report_type,
            status=status_filter,
            skip=skip,
            limit=limit,
        )

    async def get_pdf_artifact_bytes(
        self,
        report_id: uuid.UUID,
        force_regenerate: bool = False,
    ) -> Tuple[bytes, str]:
        """
        Retrieves the PDF binary bytes and safe download filename for a given report.
        If the report exists but the PDF has not yet been generated on disk (or was generated as JSON),
        it compiles the PDF dynamically from report_metadata, saves it to persistent storage,
        and updates the database record.
        """
        report = await self.get_report_by_id(report_id)
        download_filename = f"paddy_disease_report_{report.id}.pdf"

        # 1. If report already has file_path pointing to an existing valid PDF and not force_regenerate
        if not force_regenerate and report.file_format == "pdf" and report.file_path:
            filename_part = Path(report.file_path).name
            # Verify that the artifact belongs to the requested report
            if report.id.hex[:8] not in filename_part and str(report.id) not in filename_part:
                logger.warning(
                    "Security check: Artifact filename '%s' does not match report ID '%s'. Re-compiling...",
                    filename_part,
                    report_id,
                )
            else:
                try:
                    pdf_bytes = PDFReportService.read_pdf_artifact(report.file_path)
                    return pdf_bytes, download_filename
                except (FileNotFoundError, ValueError) as read_err:
                    logger.warning(
                        "Cached PDF artifact for report '%s' missing/corrupted ('%s'): %s. Re-compiling...",
                        report_id,
                        report.file_path,
                        read_err,
                    )

        # 2. Compile PDF dynamically from stored report_metadata
        metadata = report.report_metadata or {}
        if not metadata:
            logger.warning("Report '%s' has no diagnostic metadata to compile PDF.", report.id)
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Report '{report.id}' does not contain diagnostic metadata to compile artifact.",
            )

        try:
            pdf_bytes = PDFReportService.generate_pdf_bytes(
                report_id=report.id,
                metadata=metadata,
                title=report.title,
                summary=report.summary,
            )
        except Exception as gen_err:
            logger.error("Failed to compile PDF for report '%s': %s", report.id, gen_err, exc_info=True)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to compile PDF report artifact. Please try again later.",
            ) from gen_err

        # 3. Save artifact to storage
        artifact_key = PDFReportService.save_pdf_artifact(
            report_id=report.id,
            prediction_id=report.prediction_id,
            pdf_bytes=pdf_bytes,
        )

        # 4. Update report record in PostgreSQL
        try:
            report.file_path = artifact_key
            report.file_format = "pdf"
            report.file_size_bytes = len(pdf_bytes)
            await self.session.commit()
            logger.info("Updated report '%s' with fresh PDF artifact key '%s'.", report.id, artifact_key)
        except Exception as update_err:
            await self.session.rollback()
            logger.warning("Failed to update report record metadata after PDF compile: %s", update_err)

        return pdf_bytes, download_filename
